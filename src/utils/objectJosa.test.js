// 담기 토스트(S35)의 「…을/를 장바구니에 담았어요」 — 상품 이름 뒤에 규격이 붙어 끝 글자가 숫자·단위인 일이 많다.
import { objectJosa } from './customerStores';

test.each([
  ['농심 메론킥 60g', '을'],   // 그램
  ['코카콜라 1.5L', '를'],     // 리터
  ['우유 500ml', '를'],
  ['쌀 10kg', '을'],
  ['계란 30', '을'],           // 삼십
  ['라면 5', '를'],            // 오
  ['사과', '를'],
  ['메론킥', '을'],
  ['Coca-Cola', '을(를)'],     // 읽는 소리를 모르면 둘 다 적는다
])('%s → %s', (word, josa) => {
  expect(objectJosa(word)).toBe(josa);
});
